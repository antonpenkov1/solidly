import Foundation

/// Tummi's first-foods database.
///
/// Ages are the ones the cited bodies actually publish. Where guidance differs between
/// ESPGHAN (Europe) and the AAP (US) — for example on when allergens may start — the
/// earlier age is used and the difference is stated in `caution`, because delaying
/// allergens is the choice with evidence of harm behind it.
///
/// Nothing here is a gate. A food that is "not yet" still logs; the app explains, it
/// does not forbid. The only red limits are the ones with a safety mechanism behind
/// them: botulism spores in honey, mercury in predatory fish, choking shapes.
enum FoodLibrary {

    private static func f(
        _ id: String,
        _ name: LocalizedText,
        _ emoji: String,
        _ group: FoodGroup,
        from earliestMonth: Int,
        notBefore hardLimitMonth: Int? = nil,
        allergen: Allergen? = nil,
        choking: ChokingRisk = .low,
        nutrients: [NutrientTag] = [],
        early serveEarly: LocalizedText,
        later serveLater: LocalizedText,
        caution: LocalizedText? = nil,
        sources sourceIds: [String] = ["who.cf2023", "espghan.cf2017"]
    ) -> Food {
        Food(
            id: id, name: name, emoji: emoji, group: group,
            earliestMonth: earliestMonth, hardLimitMonth: hardLimitMonth,
            allergen: allergen, choking: choking, nutrients: nutrients,
            serveEarly: serveEarly, serveLater: serveLater,
            caution: caution, sourceIds: sourceIds
        )
    }

    static let all: [Food] = vegetables + fruits + grains + proteins + legumes + dairy + nutsSeeds + fats + holdOff

    private static let index: [String: Food] = Dictionary(uniqueKeysWithValues: all.map { ($0.id, $0) })

    static func food(_ id: String) -> Food? { index[id] }

    static func foods(_ ids: [String]) -> [Food] { ids.compactMap { index[$0] } }

    static var allergenFoods: [Food] { all.filter { $0.allergen != nil } }

    static func foods(in group: FoodGroup) -> [Food] { all.filter { $0.group == group } }

    static func search(_ query: String) -> [Food] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        guard !q.isEmpty else { return all }
        return all.filter {
            $0.name.en.lowercased().contains(q) || $0.name.ru.lowercased().contains(q)
        }
    }

